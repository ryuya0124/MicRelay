require "bundler"
require "json"
require "digest"
require "find"
require "fileutils"

root = File.expand_path("..", __dir__)
entries = Bundler.load.specs.sort_by(&:name).map do |spec|
  files = []
  Find.find(spec.full_gem_path) do |path|
    if File.directory?(path)
      Find.prune if path != spec.full_gem_path && %w[test tests spec specs fixtures templates examples benchmark benchmarks].include?(File.basename(path))
      next
    end
    files << path if File.basename(path).match?(/\A(?:[\w-]*licen[cs]e|copying|copyright|notice|bsdl|legal)(?:\.|\z)/i)
  end
  files.unshift(File.join(root, "scripts", "license_sources", "bundler-LICENSE.md")) if spec.name == "bundler"
  files.uniq!
  raise "License text missing for #{spec.name} #{spec.version}" if files.empty?
  texts = files.sort.map do |path|
    name = path.start_with?(spec.full_gem_path) ? path.delete_prefix(spec.full_gem_path + "/") : File.basename(path)
    text = File.read(path, encoding: "UTF-8").encode("UTF-8", invalid: :replace, undef: :replace)
    "--- #{name} ---\n\n#{text.strip}"
  end
  { name: spec.name, version: spec.version.to_s, licenses: spec.licenses,
    homepage: spec.homepage.to_s, scope: "development", text: texts.join("\n\n"),
    sha256: Digest::SHA256.hexdigest(texts.join("\n\n")) }
end
resource = File.join(root, "MicRelay", "Resources", "ThirdPartyLicenses.json")
FileUtils.mkdir_p(File.dirname(resource))
File.write(resource, JSON.pretty_generate(entries) + "\n")
notice = "# Third-party notices\n\nMicRelay does not bundle third-party runtime libraries. Apple frameworks are supplied by the operating system.\nThe following notices cover the exact Fastlane/Bundler development-tool versions in Gemfile.lock,\nincluding available notices for vendored components. They are not part of the app's audio processing path.\n\nGenerated by `bundle exec ruby scripts/generate_licenses.rb`. Do not edit this file manually.\n\n"
entries.each do |entry|
  notice << "## #{entry[:name]} #{entry[:version]}\n\n"
  notice << "License identifiers: #{entry[:licenses].empty? ? 'See full license text below' : entry[:licenses].join(', ')}\n\n"
  notice << "Project: #{entry[:homepage]}\n\n#{entry[:text]}\n\n"
end
File.write(File.join(root, "THIRD_PARTY_NOTICES.md"), notice)
puts "Generated #{entries.length} package notices (#{File.size(resource)} bytes)"
